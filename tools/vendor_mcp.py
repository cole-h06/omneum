"""Reproduce the namespaced MCP fork from the hash-pinned public source release.

No downloads or extraction: pass the public sdist explicitly. --check compares
every generated byte, including the license and provenance, without changing it.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import tarfile


VERSION = "1.30.0"
REVISION = "8c2fa6eabacde869d75568e33b9d466b58c2f512"
SHA256 = "445414625fce5c295faa505bb11bacece661ab6f4028d57c935db57820b7a3e4"
URL = "https://files.pythonhosted.org/packages/ba/93/0142dc84a666daf8ad51a34268f34c12fd6fda4f3810c4be2504eecc8212/mcp-1.30.0.tar.gz"
ROOT = Path(__file__).resolve().parents[1]


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"upstream patch context changed: {old!r}")
    return text.replace(old, new)


def patch(name, data):
    if not name.endswith(".py"):
        return data
    text = data.decode()
    text = re.sub(r"^(\s*from )mcp(?=[ .])", r"\1omneum.mcp", text, flags=re.M)
    text = re.sub(r"^(\s*import )mcp(?=\.)", r"\1omneum.mcp", text, flags=re.M)
    text = re.sub(r"^import mcp$", "import omneum.mcp as mcp", text, flags=re.M)
    # The bundled distribution has no 'mcp' dist-info; retain the SDK wire version.
    if name == "server/fastmcp/__init__.py":
        text = replace_once(text, '__version__ = version("mcp")', f'__version__ = "{VERSION}"')
        text = text.replace("from importlib.metadata import version\n", "")
    elif name == "server/lowlevel/server.py":
        text = replace_once(text, 'pkg_version("mcp")', f'"{VERSION}"')
    elif name in ("server/__main__.py", "cli/cli.py"):
        text = replace_once(text, 'importlib.metadata.version("mcp")', f'"{VERSION}"')
    if name == "client/auth/extensions/client_credentials.py":
        text = replace_once(text, "import jwt\n", "import jwt\n\nfrom omneum._crypto import require_crypto\n")
        text = replace_once(
            text, "            return jwt.encode(claims, self.signing_key, algorithm=self.signing_algorithm)",
            "            if self.signing_algorithm in jwt.algorithms.requires_cryptography:\n"
            "                require_crypto()\n"
            "            return jwt.encode(claims, self.signing_key, algorithm=self.signing_algorithm)",
        )
        text = replace_once(
            text, "            assertion = jwt.encode(\n",
            "            if (self.jwt_signing_algorithm or 'RS256') in jwt.algorithms.requires_cryptography:\n"
            "                require_crypto()\n"
            "            assertion = jwt.encode(\n",
        )
    # Normalize upstream trailing whitespace for a clean reviewable source diff.
    # No protocol wire literals use trailing line whitespace.
    return "\n".join(line.rstrip() for line in text.split("\n")).encode()


def generated(sdist):
    if hashlib.sha256(sdist.read_bytes()).hexdigest() != SHA256:
        raise ValueError("upstream source SHA256 mismatch")
    prefix = f"mcp-{VERSION}/"
    files = {}
    with tarfile.open(sdist) as archive:
        for member in archive:
            if member.isfile() and member.name.startswith(prefix + "src/mcp/"):
                name = member.name.removeprefix(prefix + "src/mcp/")
                if name in files or ".." in Path(name).parts:
                    raise ValueError("unsafe or duplicate upstream member")
                files[name] = patch(name, archive.extractfile(member).read())
        files["LICENSE"] = archive.extractfile(prefix + "LICENSE").read()
        project = archive.extractfile(prefix + "pyproject.toml").read().decode()
        # Upstream coverage aliases name its hosted runners. They are public
        # build configuration, not dependency metadata or end-user paths.
        project = replace_once(project, "/home/runner/work/python-sdk/python-sdk/src/",
                               "/build/upstream/python-sdk/src/")
        project = replace_once(project, r"D:\a\python-sdk\python-sdk\src",
                               "/build/upstream/python-sdk/src/")
        files["UPSTREAM-PYPROJECT.toml"] = project.encode()
    manifest = {
        "upstream": "https://github.com/modelcontextprotocol/python-sdk",
        "version": VERSION, "revision": REVISION,
        "sdist": {"url": URL, "sha256": SHA256},
        "namespace": "omneum.mcp",
        "distribution": "bundled in the omneum PyPI wheel and sdist; no separate SDK distribution",
        "patch": "tools/vendor_mcp.py (namespace, version lookup, crypto guard, whitespace and coverage-path normalization)",
        "files": {name: hashlib.sha256(data).hexdigest() for name, data in sorted(files.items())},
    }
    files["UPSTREAM.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sdist", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = generated(args.sdist)
    destination = ROOT / "omneum/mcp"
    actual = {p.relative_to(destination).as_posix(): p.read_bytes()
              for p in destination.rglob("*") if p.is_file() and "__pycache__" not in p.parts}
    if args.check:
        if files != actual:
            raise SystemExit("bundled MCP differs from the reproducible upstream fork")
    else:
        if set(actual) - set(files):
            raise SystemExit("unexpected files in bundled MCP; review before regeneration")
        for name, data in files.items():
            path = destination / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"{'Verified' if args.check else 'Generated'} {len(files)} bundled MCP files")


if __name__ == "__main__":
    main()
